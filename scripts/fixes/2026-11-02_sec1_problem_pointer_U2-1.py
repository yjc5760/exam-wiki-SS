def build(qid, d):
    s = HDR.format(id=qid)
    s += "### 常見誤讀\n\n| 項目 | 正確判讀 | 常見誤讀 |\n|------|---------|---------|\n"
    for r in d["rows"]:
        s += "| " + " | ".join(r) + " |\n"
    s += "\n**本解記號：** " + d["sym"] + "\n\n---\n\n"
    return s


for qid, d in T.items():
    p = os.path.join(REPO, "raw/solutions", qid, f"{qid}.md")
    t = open(p, encoding="utf-8").read()
