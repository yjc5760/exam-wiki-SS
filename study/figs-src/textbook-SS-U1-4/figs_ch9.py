def _box(x, y, w, h, t, c, fill='#fff', size=15, lines=None):
    o = R(x, y, w, h, fill, c, 2, 9)
    if lines:
        o += T(x + w / 2, y + 22, t, size, c, 'middle', 'bold')
        for i, s in enumerate(lines):
            o += T(x + w / 2, y + 44 + i * 21, s, 14, INK, 'middle')
    else:
        o += T(x + w / 2, y + h / 2 + 5, t, size, c, 'middle', 'bold')
    return o


def _dia(cx, cy, w, h, t, c=KEY):
    o = P([(cx, cy - h / 2), (cx + w / 2, cy), (cx, cy + h / 2), (cx - w / 2, cy)], c, 2, fill=KEY2, close=True)
    o += T(cx, cy + 5, t, 15, c, 'middle', 'bold')
    return o


